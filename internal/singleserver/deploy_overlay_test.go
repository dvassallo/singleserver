func TestMergeDeployOverlayMergesMappingsAndReplacesScalarsAndSequences(t *testing.T) {
	generated := overlayTestGenerated(t, AppConfig{
		Repo:    "acme/scoreboard",
		Hosts:   []string{"scoreboard.example.com"},
		Storage: &StorageConfig{Path: "/srv/storage/scoreboard", Mount: "/storage"},
	})

	config := mergeOverlayForTest(t, generated, strings.Join([]string{
		"volumes:",
		"  - /srv/cache:/cache",
		"proxy:",
		"  response_timeout: 60",
		"  healthcheck:",
		"    interval: 5",
		"",
	}, "\n"))

	volumes := config["volumes"].([]any)
	if len(volumes) != 1 || volumes[0] != "/srv/cache:/cache" {
		t.Fatalf("expected overlay volumes to replace generated ones, got %#v", volumes)
	}
	proxy := config["proxy"].(map[string]any)
	if proxy["response_timeout"] != 60 {
		t.Fatalf("expected new proxy key, got %#v", proxy)
	}
	if proxy["app_port"] != 80 || proxy["forward_headers"] != true {
		t.Fatalf("expected generated proxy keys to survive, got %#v", proxy)
	}
	hosts := proxy["hosts"].([]any)
	if len(hosts) != 1 || hosts[0] != "scoreboard.example.com" {
		t.Fatalf("expected generated proxy hosts, got %#v", hosts)
	}
	healthcheck := proxy["healthcheck"].(map[string]any)
	if healthcheck["interval"] != 5 || healthcheck["path"] != "/" || healthcheck["timeout"] != 1 {
		t.Fatalf("unexpected healthcheck: %#v", healthcheck)
	}
}

func TestMergeDeployOverlayResolvesAliases(t *testing.T) {
	generated := overlayTestGenerated(t, AppConfig{Repo: "acme/scoreboard"})

	merged, err := mergeDeployOverlay(generated, []byte("x-tag: &tag scoreboard\nlogging:\n  options:\n    tag: *tag\n"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(merged), "*tag") || strings.Contains(string(merged), "&tag") {
		t.Fatalf("expected aliases to be resolved, got:\n%s", merged)
	}
	var config map[string]any
	if err := yaml.Unmarshal(merged, &config); err != nil {
		t.Fatal(err)
	}
	if config["logging"].(map[string]any)["options"].(map[string]any)["tag"] != "scoreboard" {
		t.Fatalf("unexpected logging: %#v", config["logging"])
	}
}

