func TestMergeDeployOverlayAppendsNewTopLevelKeysAfterGeneratedOnes(t *testing.T) {
	generated := overlayTestGenerated(t, AppConfig{Repo: "acme/scoreboard"})

	merged, err := mergeDeployOverlay(generated, []byte("boot:\n  limit: 1\n"))
	if err != nil {
		t.Fatal(err)
	}
	generatedKeys := topLevelKeys(t, generated)
	mergedKeys := topLevelKeys(t, merged)
	want := append(append([]string{}, generatedKeys...), "boot")
	if strings.Join(mergedKeys, ",") != strings.Join(want, ",") {
		t.Fatalf("unexpected key order: %v, want %v", mergedKeys, want)
	}
}

func TestMergeDeployOverlayEnvClearKeepsGeneratedSecrets(t *testing.T) {
	generated := overlayTestGenerated(t, AppConfig{Repo: "acme/scoreboard", SecretEnvKeys: []string{"DATABASE_URL", "STRIPE_KEY"}})

	config := mergeOverlayForTest(t, generated, "env:\n  clear:\n    LOG_LEVEL: debug\n")

	env := config["env"].(map[string]any)
	secrets := env["secret"].([]any)
	if len(secrets) != 2 || secrets[0] != "DATABASE_URL" || secrets[1] != "STRIPE_KEY" {
		t.Fatalf("expected generated secrets to survive, got %#v", secrets)
	}
	clear := env["clear"].(map[string]any)
	if clear["LOG_LEVEL"] != "debug" {
		t.Fatalf("expected overlay clear env, got %#v", clear)
	}
}

