func TestMergeDeployConfigCommandWritesMergedFile(t *testing.T) {
	dir := t.TempDir()
	generated := overlayTestGenerated(t, AppConfig{Repo: "acme/scoreboard"})
	t.Setenv(generatedDeployYAMLEnv, string(generated))
	overlayPath := filepath.Join(dir, "overlay.yml")
	outputPath := filepath.Join(dir, "deploy.yml")
	if err := os.WriteFile(overlayPath, []byte("boot:\n  limit: 1\n"), 0644); err != nil {
		t.Fatal(err)
	}

	if err := runCLI([]string{mergeDeployConfigCommand, overlayPath, outputPath}, nil, &bytes.Buffer{}); err != nil {
		t.Fatal(err)
	}
	body, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(body), string(generated)) || !strings.HasSuffix(string(body), "boot:\n  limit: 1\n") {
		t.Fatalf("unexpected merged file:\n%s", body)
	}

	if err := os.WriteFile(overlayPath, []byte("registry: {}\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := runCLI([]string{mergeDeployConfigCommand, overlayPath, outputPath}, nil, &bytes.Buffer{}); err == nil {
		t.Fatal("expected managed key to fail the merge command")
	}
}

func TestMergeDeployOverlayOverridesDefaultLogging(t *testing.T) {
	generated := overlayTestGenerated(t, AppConfig{Repo: "acme/scoreboard"})

	config := mergeOverlayForTest(t, generated, "logging:\n  driver: json-file\n  options:\n    max-size: 10m\n")

	logging := config["logging"].(map[string]any)
	if logging["driver"] != "json-file" {
		t.Fatalf("expected overlay driver, got %#v", logging)
	}
	options := logging["options"].(map[string]any)
	if options["max-size"] != "10m" || options["tag"] != "scoreboard" {
		t.Fatalf("expected overlay options merged over the default tag, got %#v", options)
	}
}
